// Command pgsema-gen generates Go code from PostgreSQL source files.
// Currently it generates:
// - keywords.go from kwlist.h and PostgreSQL 16's pg_get_keywords()
// - node types from parsenodes.h (TODO)
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

var (
	kwlistPath = flag.String("kwlist", "", "path to PostgreSQL kwlist.h")
	pg16Path   = flag.String("pg16", "parser/testdata/pg16_keywords.tsv", "PostgreSQL 16's pg_get_keywords() (word, catcode, barelabel), tab separated")
	outDir     = flag.String("outdir", "pkg/parser", "output directory")
)

func main() {
	flag.Parse()

	if *kwlistPath != "" {
		if err := generateKeywords(*kwlistPath, *pg16Path, *outDir); err != nil {
			fmt.Fprintf(os.Stderr, "Error generating keywords: %v\n", err)
			os.Exit(1)
		}
		fmt.Println("Generated keywords.go")
	}
}

// KeywordCategory represents the PostgreSQL keyword category.
type KeywordCategory int

const (
	UnreservedKeyword KeywordCategory = iota
	ColNameKeyword
	TypeFuncNameKeyword
	ReservedKeyword
)

var categoryNames = [...]string{"UnreservedKeyword", "ColNameKeyword", "TypeFuncNameKeyword", "ReservedKeyword"}

// Keyword represents a PostgreSQL keyword.
type Keyword struct {
	Name      string // keyword text (lowercase)
	Token     string // token name in grammar
	Category  KeywordCategory
	BareLabel bool // a column label without AS (BARE_LABEL)

	// Token16, Category16 and BareLabel16 are the keyword in PostgreSQL 16:
	// Token16 is IDENT for a word PostgreSQL 16 has no keyword for, and
	// Token with _PG16 appended for one whose category or label differs.
	Token16     string
	Category16  KeywordCategory
	BareLabel16 bool
}

func generateKeywords(kwlistPath, pg16Path, outDir string) error {
	keywords, err := parseKwlist(kwlistPath)
	if err != nil {
		return err
	}
	if err := addPG16(keywords, pg16Path); err != nil {
		return err
	}
	src, err := keywordsSource(keywords)
	if err != nil {
		return err
	}
	return os.WriteFile(outDir+"/keywords.go", src, 0o644)
}

// keywordsSource is keywords.go for keywords, gofmt'd.
func keywordsSource(keywords []Keyword) ([]byte, error) {
	var f bytes.Buffer
	f.WriteString(`// Code generated by pgsema-gen. DO NOT EDIT.
// Source: PostgreSQL kwlist.h and testdata/pg16_keywords.tsv

package parser

// KeywordCategory represents the PostgreSQL keyword category.
type KeywordCategory int

const (
	UnreservedKeyword KeywordCategory = iota
	ColNameKeyword
	TypeFuncNameKeyword
	ReservedKeyword
)

// Keyword represents a PostgreSQL keyword.
type Keyword struct {
	Name      string
	Token     int
	Category  KeywordCategory
	BareLabel bool
	// Token16, Category16 and BareLabel16 are the keyword in PostgreSQL 16,
	// from its pg_get_keywords(). Token16 is IDENT for a word that is no
	// keyword in PostgreSQL 16, and a token of its own for one whose
	// category or label differs there.
	Token16     int
	Category16  KeywordCategory
	BareLabel16 bool
}

// Keywords is the list of all PostgreSQL keywords.
// The list is sorted by keyword name for binary search.
var Keywords = []Keyword{
`)
	n16 := 0
	for _, kw := range keywords {
		if kw.Token16 != "IDENT" {
			n16++
		}
		fmt.Fprintf(&f, "\t{%q, %s, %s, %t, %s, %s, %t},\n", kw.Name, kw.Token, categoryNames[kw.Category], kw.BareLabel,
			kw.Token16, categoryNames[kw.Category16], kw.BareLabel16)
	}
	fmt.Fprintf(&f, `}

// keywordMap maps keyword names to their definitions.
var keywordMap = func() map[string]*Keyword {
	m := make(map[string]*Keyword, len(Keywords))
	for i := range Keywords {
		m[Keywords[i].Name] = &Keywords[i]
	}
	return m
}()

// keywordMap16 maps the names of PostgreSQL 16's keywords to their
// definitions there: Token, Category and BareLabel are PostgreSQL 16's.
var keywordMap16 = func() map[string]*Keyword {
	m := make(map[string]*Keyword, %d)
	for i := range Keywords {
		k := Keywords[i]
		if k.Token16 == IDENT {
			continue
		}
		k.Token, k.Category, k.BareLabel = k.Token16, k.Category16, k.BareLabel16
		m[k.Name] = &k
	}
	return m
}()

// LookupKeyword looks up a keyword by name, ignoring ASCII case only, as
// PostgreSQL's ScanKeywordLookup does. Returns nil if not found.
func LookupKeyword(name string) *Keyword {
	return keywordMap[downcase(name)]
}
`, n16)
	return format.Source(f.Bytes())
}

// addPG16 fills in the PostgreSQL 16 columns of keywords from path, the
// output of PostgreSQL 16's select word, catcode, barelabel from
// pg_get_keywords(), tab separated under a header line.
func addPG16(keywords []Keyword, path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	byName := make(map[string]*Keyword, len(keywords))
	for i := range keywords {
		keywords[i].Token16 = "IDENT"
		byName[keywords[i].Name] = &keywords[i]
	}
	lines := strings.Split(strings.TrimSuffix(string(data), "\n"), "\n")
	if lines[0] != "word\tcatcode\tbarelabel" {
		return fmt.Errorf("%s: header %q, want word, catcode, barelabel", path, lines[0])
	}
	for _, line := range lines[1:] {
		cols := strings.Split(line, "\t")
		if len(cols) != 3 {
			return fmt.Errorf("%s: bad line %q", path, line)
		}
		kw := byName[cols[0]]
		if kw == nil {
			return fmt.Errorf("%s: %q is a PostgreSQL 16 keyword kwlist.h does not have", path, cols[0])
		}
		cat := strings.Index("UCTR", cols[1])
		if len(cols[1]) != 1 || cat < 0 || cols[2] != "t" && cols[2] != "f" {
			return fmt.Errorf("%s: bad line %q", path, line)
		}
		kw.Category16, kw.BareLabel16 = KeywordCategory(cat), cols[2] == "t"
		kw.Token16 = kw.Token
		if kw.Category16 != kw.Category || kw.BareLabel16 != kw.BareLabel {
			kw.Token16 = kw.Token + "_PG16"
		}
	}
	return nil
}

func parseKwlist(path string) ([]Keyword, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	// PG_KEYWORD("abort", ABORT_P, UNRESERVED_KEYWORD, BARE_LABEL)
	re := regexp.MustCompile(`PG_KEYWORD\("([^"]+)",\s*(\w+),\s*(\w+),\s*(\w+)\)`)

	var keywords []Keyword
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := scanner.Text()
		matches := re.FindStringSubmatch(line)
		if matches == nil {
			continue
		}

		name := matches[1]
		token := matches[2]
		catStr := matches[3]

		var cat KeywordCategory
		switch catStr {
		case "UNRESERVED_KEYWORD":
			cat = UnreservedKeyword
		case "COL_NAME_KEYWORD":
			cat = ColNameKeyword
		case "TYPE_FUNC_NAME_KEYWORD":
			cat = TypeFuncNameKeyword
		case "RESERVED_KEYWORD":
			cat = ReservedKeyword
		default:
			return nil, fmt.Errorf("unknown keyword category: %s", catStr)
		}

		var bare bool
		switch matches[4] {
		case "BARE_LABEL":
			bare = true
		case "AS_LABEL":
		default:
			return nil, fmt.Errorf("unknown keyword label: %s", matches[4])
		}

		keywords = append(keywords, Keyword{
			Name:      name,
			Token:     token,
			Category:  cat,
			BareLabel: bare,
		})
	}

	return keywords, scanner.Err()
}
