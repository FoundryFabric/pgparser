package parser

import (
	"bufio"
	"encoding/json"
	"errors"
	"os"
	"testing"
)

// constraintAttributeCase is one statement of
// testdata/constraint_attribute_pg16.jsonl and what PostgreSQL 16.15 did with
// it: an error with its SQLSTATE, message and 0-based byte position (-1 where
// PostgreSQL gave none), or no code when it parsed.
type constraintAttributeCase struct {
	SQL      string `json:"sql"`
	Code     string `json:"code"`
	Message  string `json:"message"`
	Position int    `json:"position"`
}

// TestConstraintAttributesArePostgreSQL16s pins PostgreSQL 16's answers for
// 1,741 statements its grammar accepts but a constraint's grammar action may
// refuse: DEFERRABLE, NOT DEFERRABLE, INITIALLY, NOT VALID and NO INHERIT,
// alone, repeated and in conflict, on each kind of table and domain
// constraint, a column's REFERENCES, ALTER CONSTRAINT and a constraint
// trigger; a column list with SET NULL or SET DEFAULT in ON UPDATE; and
// GENERATED BY DEFAULT on a generated column, with the forms around each
// that PostgreSQL accepts.
func TestConstraintAttributesArePostgreSQL16s(t *testing.T) {
	f, err := os.Open("testdata/constraint_attribute_pg16.jsonl")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	var cases []constraintAttributeCase
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		var c constraintAttributeCase
		if err := json.Unmarshal(sc.Bytes(), &c); err != nil {
			t.Fatal(err)
		}
		cases = append(cases, c)
	}
	if err := sc.Err(); err != nil {
		t.Fatal(err)
	}
	if len(cases) != 1741 {
		t.Fatalf("%d cases, want 1741", len(cases))
	}
	for _, c := range cases {
		_, err := Parse(c.SQL)
		if c.Code == "" {
			if err != nil {
				t.Errorf("Parse(%q) = %v, want it parsed", c.SQL, err)
			}
			continue
		}
		var pe *ParseError
		if !errors.As(err, &pe) || pe.Code != c.Code || pe.Message != c.Message || pe.Position != c.Position {
			t.Errorf("Parse(%q) = %v, want %s %s at %d", c.SQL, err, c.Code, c.Message, c.Position)
		}
	}
}
