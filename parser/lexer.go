// Package parser implements a PostgreSQL-compatible SQL lexer and parser.
// This lexer is a direct translation of PostgreSQL's scan.l.
package parser

import (
	"fmt"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"
)

// Token types returned by the lexer (internal, prefixed with lex_).
// These are mapped to parser token constants in parse.go.
// Keywords are defined in keywords.go using constants from parser.go.
// Non-keyword tokens start after all keywords to avoid conflicts.
// Base token value for keywords (must be > 256 to avoid ASCII conflicts)
// This value is used in the lexer for keyword token recognition.
// The actual keyword constants are generated by goyacc in parser.go.
const keywordTokenBase = 258

// Non-keyword token base - must be after all keyword tokens
// Keywords use 258 + 0..491 (492 keywords), so we start at 800
const nonKeywordTokenBase = 800

const (
	// Special tokens
	lex_EOF = 0
)

// Internal lexer token types for non-keywords.
// These start at nonKeywordTokenBase and are mapped to parser constants in parse.go.
const (
	lex_ICONST = nonKeywordTokenBase + iota
	lex_FCONST
	lex_SCONST  // String constant
	lex_BCONST  // Bit string constant (B'...')
	lex_XCONST  // Hex string constant (X'...')
	lex_USCONST // Unicode string constant (U&'...')
	lex_IDENT
	lex_UIDENT         // Unicode identifier (U&"...")
	lex_TYPECAST       // ::
	lex_DOT_DOT        // ..
	lex_COLON_EQUALS   // :=
	lex_EQUALS_GREATER // =>
	lex_LESS_EQUALS    // <=
	lex_GREATER_EQUALS // >=
	lex_NOT_EQUALS     // <> or !=
	lex_PARAM          // $1, $2, etc.
	lex_Op
)

// LexerState represents the current state of the lexer (for string/comment handling).
type LexerState int

const (
	stateInitial LexerState = iota
	stateXB                 // bit string literal
	stateXC                 // extended C-style comments
	stateXD                 // delimited identifiers (double-quoted)
	stateXH                 // hexadecimal byte string
	stateXQ                 // standard quoted strings
	stateXQS                // quote stop (detect continued strings)
	stateXE                 // extended quoted strings (backslash escapes)
	stateXDOLQ              // dollar-quoted strings
	stateXUI                // quoted identifier with Unicode escapes
	stateXUS                // quoted string with Unicode escapes
)

// Token represents a lexical token.
type Token struct {
	Type int    // Token type (IDENT, ICONST, keyword token, etc.)
	Str  string // String value for identifiers, operators, string literals
	Ival int64  // Integer value for ICONST
	Loc  int    // Byte offset in the source text
}

// Lexer implements a PostgreSQL-compatible SQL lexer.
type Lexer struct {
	input string // Input SQL text
	pos   int    // Current position in input (byte offset)
	start int    // Start position of current token

	state              LexerState // Current lexer state
	stateBeforeStrStop LexerState // State before entering xqs

	// Literal buffer for building string/identifier values
	literalbuf strings.Builder

	// Dollar quote delimiter
	dolqstart string

	// Comment nesting depth
	xcdepth int

	// Configuration
	StandardConformingStrings bool // If true, backslash is not escape in standard strings
	BackslashQuote            int  // 0=off, 1=on, 2=safe_encoding
	EscapeStringWarning       bool

	// Warning tracking
	warnOnFirstEscape bool
	sawNonASCII       bool

	// Location tracking
	savedLoc int

	// opRun lets lexOperator lex a run of operator characters in linear time.
	opRun opRun
	// opScanSteps counts the input positions lexOperator's scans examine.
	// Only tests read it, to check that lexing a run is linear in its length.
	opScanSteps int

	// Err is the first error the lexer met, a *ParseError carrying
	// PostgreSQL's SQLSTATE, message and position. The lexer returns EOF from
	// then on, as PostgreSQL's scanner stops at its first error.
	Err error

	// noticeHandler, when non-nil, receives each notice the lexer raises, in
	// source order. Only Parse sets it, from WithNoticeHandler.
	noticeHandler func(Notice)
}

// BackslashQuote values
const (
	BackslashQuoteOff = iota
	BackslashQuoteOn
	BackslashQuoteSafeEncoding
)

// NewLexer creates a new lexer for the given input.
func NewLexer(input string) *Lexer {
	return &Lexer{
		input:                     input,
		pos:                       0,
		state:                     stateInitial,
		StandardConformingStrings: true,
		BackslashQuote:            BackslashQuoteSafeEncoding,
		EscapeStringWarning:       true,
	}
}

// NextToken returns the next token from the input.
func (l *Lexer) NextToken() Token {
	for {
		if l.pos >= len(l.input) {
			// At EOF - if we're in a string state, that's an error
			// If we're in quote-stop state, return the completed string
			if l.state == stateXQS {
				return l.lexQuoteContinue()
			}
			return Token{Type: lex_EOF, Loc: l.pos}
		}

		switch l.state {
		case stateInitial:
			l.start = l.pos
			return l.lexInitial()
		case stateXC:
			l.lexComment()
			continue
		case stateXB, stateXH:
			return l.lexBitOrHexString()
		case stateXQ, stateXE, stateXUS:
			return l.lexQuotedString()
		case stateXQS:
			return l.lexQuoteContinue()
		case stateXD, stateXUI:
			return l.lexDelimitedIdent()
		case stateXDOLQ:
			return l.lexDollarQuote()
		default:
			return l.failAt("XX000", fmt.Sprintf("unknown lexer state: %d", l.state), l.start, "")
		}
	}
}

// lexInitial handles tokens in the initial state.
func (l *Lexer) lexInitial() Token {
	l.skipWhitespace()
	if l.pos >= len(l.input) {
		return Token{Type: lex_EOF, Loc: l.pos}
	}

	l.start = l.pos
	ch := l.input[l.pos]

	// Check for C-style comment start
	if ch == '/' && l.pos+1 < len(l.input) && l.input[l.pos+1] == '*' {
		l.pos += 2
		l.xcdepth = 0
		l.state = stateXC
		// Return to main loop to handle comment
		return l.NextToken()
	}

	// Check for SQL comment
	if ch == '-' && l.pos+1 < len(l.input) && l.input[l.pos+1] == '-' {
		l.skipLineComment()
		return l.NextToken()
	}

	// Bit string: B'...'
	if (ch == 'b' || ch == 'B') && l.pos+1 < len(l.input) && l.input[l.pos+1] == '\'' {
		l.pos += 2
		l.state = stateXB
		l.literalbuf.Reset()
		l.literalbuf.WriteByte('b')
		return l.NextToken()
	}

	// Hex string: X'...'
	if (ch == 'x' || ch == 'X') && l.pos+1 < len(l.input) && l.input[l.pos+1] == '\'' {
		l.pos += 2
		l.state = stateXH
		l.literalbuf.Reset()
		l.literalbuf.WriteByte('x')
		return l.NextToken()
	}

	// National character: N'...' -> treat as NCHAR followed by string
	if (ch == 'n' || ch == 'N') && l.pos+1 < len(l.input) && l.input[l.pos+1] == '\'' {
		// Look up NCHAR keyword
		kw := LookupKeyword("nchar")
		if kw != nil {
			l.pos++ // consume only 'n'
			return Token{Type: kw.Token, Str: kw.Name, Loc: l.start}
		}
		// If NCHAR isn't a keyword, return 'n' as identifier
		l.pos++
		return Token{Type: lex_IDENT, Str: "n", Loc: l.start}
	}

	// Extended quoted string: E'...'
	if (ch == 'e' || ch == 'E') && l.pos+1 < len(l.input) && l.input[l.pos+1] == '\'' {
		l.pos += 2
		l.state = stateXE
		l.warnOnFirstEscape = false
		l.sawNonASCII = false
		l.literalbuf.Reset()
		return l.NextToken()
	}

	// Unicode string: U&'...'
	if (ch == 'u' || ch == 'U') && l.pos+1 < len(l.input) && l.input[l.pos+1] == '&' {
		if l.pos+2 < len(l.input) && l.input[l.pos+2] == '\'' {
			if !l.StandardConformingStrings {
				return l.failAt("0A000", "unsafe use of string constant with Unicode escapes", l.start, "")
			}
			l.pos += 3
			l.state = stateXUS
			l.literalbuf.Reset()
			return l.NextToken()
		}
		// Unicode identifier: U&"..."
		if l.pos+2 < len(l.input) && l.input[l.pos+2] == '"' {
			l.pos += 3
			l.state = stateXUI
			l.literalbuf.Reset()
			return l.NextToken()
		}
		// Just 'U&' without quote - return 'u' as identifier
		l.pos++
		ident := downcase("u")
		return Token{Type: lex_IDENT, Str: ident, Loc: l.start}
	}

	// Standard quoted string: '...'
	if ch == '\'' {
		l.pos++
		l.warnOnFirstEscape = true
		l.sawNonASCII = false
		if l.StandardConformingStrings {
			l.state = stateXQ
		} else {
			l.state = stateXE
		}
		l.literalbuf.Reset()
		return l.NextToken()
	}

	// Double-quoted identifier: "..."
	if ch == '"' {
		l.pos++
		l.state = stateXD
		l.literalbuf.Reset()
		return l.NextToken()
	}

	// Dollar-quoted string: $tag$...$tag$
	if ch == '$' {
		if tag := l.scanDollarTag(); tag != "" {
			l.dolqstart = tag
			l.state = stateXDOLQ
			l.literalbuf.Reset()
			return l.NextToken()
		}
		// Check for parameter: $1, $2, etc.
		if l.pos+1 < len(l.input) && isDigit(l.input[l.pos+1]) {
			return l.lexParam()
		}
		// Single $ is returned as itself
		l.pos++
		return Token{Type: int(ch), Str: string(ch), Loc: l.start}
	}

	// Two-character special tokens (must check before operators)
	if l.pos+1 < len(l.input) {
		ch2 := l.input[l.pos : l.pos+2]
		switch ch2 {
		case "::":
			l.pos += 2
			return Token{Type: lex_TYPECAST, Str: "::", Loc: l.start}
		case "..":
			l.pos += 2
			return Token{Type: lex_DOT_DOT, Str: "..", Loc: l.start}
		case ":=":
			l.pos += 2
			return Token{Type: lex_COLON_EQUALS, Str: ":=", Loc: l.start}
		}
	}

	// Operators (including multi-char operators like ->, ||, etc.)
	// Must check before self-delimiting because some chars overlap
	if isOpChar(ch) {
		return l.lexOperator()
	}

	// Numbers - check for leading dot numeric BEFORE self-delimiting
	// because .5 should be parsed as a numeric, not as . followed by 5
	if ch == '.' && l.pos+1 < len(l.input) && isDigit(l.input[l.pos+1]) {
		return l.lexNumber()
	}

	// Self-delimiting characters that are NOT operator chars
	// Note: +, -, *, /, %, ^, <, >, = are handled by lexOperator above
	if isSelfOnly(ch) {
		l.pos++
		return Token{Type: int(ch), Str: string(ch), Loc: l.start}
	}

	// Numbers starting with digit
	if isDigit(ch) {
		return l.lexNumber()
	}

	// Identifiers and keywords
	if isIdentStart(ch) {
		return l.lexIdent()
	}

	// Any other character
	l.pos++
	return Token{Type: int(ch), Str: string(ch), Loc: l.start}
}

// skipWhitespace skips whitespace characters.
func (l *Lexer) skipWhitespace() {
	for l.pos < len(l.input) {
		ch := l.input[l.pos]
		if ch == ' ' || ch == '\t' || ch == '\n' || ch == '\r' || ch == '\f' || ch == '\v' {
			l.pos++
		} else if ch == '-' && l.pos+1 < len(l.input) && l.input[l.pos+1] == '-' {
			l.skipLineComment()
		} else {
			break
		}
	}
}

// skipLineComment skips a -- comment to end of line.
func (l *Lexer) skipLineComment() {
	l.pos += 2 // skip --
	for l.pos < len(l.input) {
		ch := l.input[l.pos]
		l.pos++
		if ch == '\n' || ch == '\r' {
			break
		}
	}
}

// lexComment handles C-style comments /* ... */
func (l *Lexer) lexComment() {
	for l.pos < len(l.input) {
		ch := l.input[l.pos]

		// Check for nested comment start
		if ch == '/' && l.pos+1 < len(l.input) && l.input[l.pos+1] == '*' {
			l.xcdepth++
			l.pos += 2
			continue
		}

		// Check for comment end
		if ch == '*' && l.pos+1 < len(l.input) && l.input[l.pos+1] == '/' {
			l.pos += 2
			if l.xcdepth <= 0 {
				l.state = stateInitial
				return
			}
			l.xcdepth--
			continue
		}

		l.pos++
	}

	// Reached EOF inside comment
	l.failNear("unterminated /* comment", l.start)
}

// lexBitOrHexString handles B'...' and X'...' strings.
func (l *Lexer) lexBitOrHexString() Token {
	for l.pos < len(l.input) {
		ch := l.input[l.pos]
		if ch == '\'' {
			l.pos++
			l.stateBeforeStrStop = l.state
			l.state = stateXQS
			return l.NextToken()
		}
		l.literalbuf.WriteByte(ch)
		l.pos++
	}

	if l.state == stateXB {
		return l.failNear("unterminated bit string literal", l.start)
	}
	return l.failNear("unterminated hexadecimal string literal", l.start)
}

// lexQuotedString handles '...' E'...' and U&'...' strings.
func (l *Lexer) lexQuotedString() Token {
	for l.pos < len(l.input) {
		ch := l.input[l.pos]

		// End quote - check for doubled quote first
		if ch == '\'' {
			// Check for doubled quote (escaped single quote)
			if l.pos+1 < len(l.input) && l.input[l.pos+1] == '\'' {
				l.literalbuf.WriteByte('\'')
				l.pos += 2
				continue
			}
			// Single quote - end of string, check for continuation
			l.pos++
			l.stateBeforeStrStop = l.state
			l.state = stateXQS
			return l.NextToken()
		}

		// For extended strings, handle escape sequences
		if l.state == stateXE && ch == '\\' && l.pos+1 < len(l.input) {
			l.pos++
			if !l.handleEscapeSequence() {
				return Token{Type: lex_EOF, Loc: l.start}
			}
			continue
		}

		l.literalbuf.WriteByte(ch)
		l.pos++
	}

	return l.failNear("unterminated quoted string", l.start)
}

// handleEscapeSequence processes escape sequences in E'...' strings, with
// l.pos just past the backslash. It is false when the escape is refused, the
// error recorded.
func (l *Lexer) handleEscapeSequence() bool {
	ch := l.input[l.pos]
	l.pos++

	switch ch {
	case 'b':
		l.literalbuf.WriteByte('\b')
	case 'f':
		l.literalbuf.WriteByte('\f')
	case 'n':
		l.literalbuf.WriteByte('\n')
	case 'r':
		l.literalbuf.WriteByte('\r')
	case 't':
		l.literalbuf.WriteByte('\t')
	case 'v':
		l.literalbuf.WriteByte('\v')
	case '0', '1', '2', '3', '4', '5', '6', '7':
		// Octal escape: \0 through \777
		l.pos--
		val := l.scanOctal()
		l.literalbuf.WriteByte(byte(val))
		if val > 127 {
			l.sawNonASCII = true
		}
	case 'x':
		// Hex escape: \xNN
		if l.pos < len(l.input) && isHexDigit(l.input[l.pos]) {
			val := l.scanHex(2)
			l.literalbuf.WriteByte(byte(val))
			if val > 127 {
				l.sawNonASCII = true
			}
		} else {
			l.literalbuf.WriteByte('x')
		}
	case 'u', 'U':
		return l.unicodeEscape()
	default:
		l.literalbuf.WriteByte(ch)
	}
	return true
}

// unicodeEscape reads a \uXXXX or \UXXXXXXXX escape, and a UTF-16 surrogate
// pair written as two of them, with l.pos just past the u or U. It mirrors
// scan.l's xeunicode, xeunicodefail and xeu rules and addunicode.
func (l *Lexer) unicodeEscape() bool {
	esc := l.pos - 2
	c, ok := l.scanUnicodeEscape(esc)
	if !ok {
		return false
	}
	if isUTF16SurrogateFirst(c) {
		// xeu: the next thing must be an escape holding the second half.
		second := l.pos
		if second+1 >= len(l.input) || l.input[second] != '\\' || (l.input[second+1] != 'u' && l.input[second+1] != 'U') {
			l.pos = min(second+1, len(l.input))
			l.failNear("invalid Unicode surrogate pair", second)
			return false
		}
		l.pos += 2
		low, ok := l.scanUnicodeEscape(second)
		if !ok {
			return false
		}
		if !isUTF16SurrogateSecond(low) {
			l.failNear("invalid Unicode surrogate pair", second)
			return false
		}
		c = surrogateToCodepoint(c, low)
	} else if isUTF16SurrogateSecond(c) {
		l.failNear("invalid Unicode surrogate pair", esc)
		return false
	}
	if c == 0 || c > unicode.MaxRune {
		l.failNear("invalid Unicode escape value", esc)
		return false
	}
	l.writeUnicodeChar(c)
	return true
}

// scanUnicodeEscape reads the hex digits of the escape at esc, 4 after \u and
// 8 after \U, with l.pos at the first. Fewer is 22025, as xeunicodefail.
func (l *Lexer) scanUnicodeEscape(esc int) (rune, bool) {
	n := 4
	if l.input[esc+1] == 'U' {
		n = 8
	}
	if l.pos+n > len(l.input) || !allHex(l.input[l.pos:l.pos+n]) {
		l.failAt("22025", "invalid Unicode escape", esc, "Unicode escapes must be \\uXXXX or \\UXXXXXXXX.")
		return 0, false
	}
	return rune(l.scanHex(n)), true
}

// allHex is true when every byte of s is a hex digit.
func allHex(s string) bool {
	for i := 0; i < len(s); i++ {
		if !isHexDigit(s[i]) {
			return false
		}
	}
	return true
}

// scanOctal scans an octal escape sequence.
func (l *Lexer) scanOctal() int {
	val := 0
	for i := 0; i < 3 && l.pos < len(l.input); i++ {
		ch := l.input[l.pos]
		if ch < '0' || ch > '7' {
			break
		}
		val = val*8 + int(ch-'0')
		l.pos++
	}
	return val
}

// scanHex scans n hex digits.
func (l *Lexer) scanHex(n int) int {
	val := 0
	for i := 0; i < n && l.pos < len(l.input); i++ {
		ch := l.input[l.pos]
		if !isHexDigit(ch) {
			break
		}
		val = val*16 + hexValue(ch)
		l.pos++
	}
	return val
}

// writeUnicodeChar writes a Unicode code point to the literal buffer.
func (l *Lexer) writeUnicodeChar(r rune) {
	var buf [4]byte
	n := utf8.EncodeRune(buf[:], r)
	l.literalbuf.Write(buf[:n])
}

// lexQuoteContinue handles quote continuation (string literal spanning lines).
func (l *Lexer) lexQuoteContinue() Token {
	// Check if there's whitespace with newline followed by quote
	// SQL requires at least one newline in the whitespace to continue a string
	hasNewline := false

	for l.pos < len(l.input) {
		ch := l.input[l.pos]
		if ch == ' ' || ch == '\t' || ch == '\f' || ch == '\v' {
			l.pos++
		} else if ch == '\n' || ch == '\r' {
			hasNewline = true
			l.pos++
		} else if ch == '-' && l.pos+1 < len(l.input) && l.input[l.pos+1] == '-' {
			// SQL comment - after comment there's an implicit newline
			l.skipLineComment()
			hasNewline = true
		} else {
			break
		}
	}

	// If we see a quote after whitespace with newline, continue the string
	if hasNewline && l.pos < len(l.input) && l.input[l.pos] == '\'' {
		l.pos++
		l.state = l.stateBeforeStrStop
		return l.NextToken()
	}

	// No continuation - return the completed string
	// Don't rewind position, just return from current spot
	l.state = stateInitial

	str := l.literalbuf.String()

	switch l.stateBeforeStrStop {
	case stateXB:
		return Token{Type: lex_BCONST, Str: str, Loc: l.start}
	case stateXH:
		return Token{Type: lex_XCONST, Str: str, Loc: l.start}
	case stateXQ, stateXE:
		return Token{Type: lex_SCONST, Str: str, Loc: l.start}
	case stateXUS:
		// Unicode string: U&'...'
		// Check for UESCAPE clause
		escapeChar, err := l.scanUESCAPE()
		if err != nil {
			l.Err = err
			return Token{Type: lex_EOF, Loc: l.start}
		}

		// Decode the string using the determined escape char
		decoded, ok := l.decodeUnicodeString(str, byte(escapeChar), l.start)
		if !ok {
			return Token{Type: lex_EOF, Loc: l.start}
		}

		return Token{Type: lex_USCONST, Str: decoded, Loc: l.start}
	case stateXUI:
		// Unicode identifier: U&"..."
		// Check for UESCAPE clause
		// fmt.Printf("DEBUG: checking UESCAPE for identifier %s\n", str)
		escapeChar, err := l.scanUESCAPE()
		if err != nil {
			l.Err = err
			return Token{Type: lex_EOF, Loc: l.start}
		}

		// Decode the string using the determined escape char
		decoded, ok := l.decodeUnicodeString(str, byte(escapeChar), l.start)
		if !ok {
			return Token{Type: lex_EOF, Loc: l.start}
		}

		// It's an identifier
		return Token{Type: lex_IDENT, Str: l.truncateIdentifier(decoded), Loc: l.start}
	default:
		return Token{Type: lex_SCONST, Str: str, Loc: l.start}
	}
}

// lexDelimitedIdent handles "..." identifiers.
func (l *Lexer) lexDelimitedIdent() Token {
	for l.pos < len(l.input) {
		ch := l.input[l.pos]

		// End quote
		if ch == '"' {
			l.pos++
			// Check for "" (escaped quote)
			if l.pos < len(l.input) && l.input[l.pos] == '"' {
				l.literalbuf.WriteByte('"')
				l.pos++
				continue
			}
			// End of identifier
			oldState := l.state
			l.state = stateInitial

			// If it's a Unicode identifier (U&"..."), we need to handle optional UESCAPE
			if oldState == stateXUI {
				l.stateBeforeStrStop = stateXUI
				return l.lexQuoteContinue()
			}

			str := l.literalbuf.String()
			if str == "" {
				return l.failNear("zero-length delimited identifier", l.start)
			}
			return Token{Type: lex_IDENT, Str: l.truncateIdentifier(str), Loc: l.start}
		}

		l.literalbuf.WriteByte(ch)
		l.pos++
	}

	return l.failNear("unterminated quoted identifier", l.start)
}

// lexDollarQuote handles $tag$...$tag$ strings.
func (l *Lexer) lexDollarQuote() Token {
	for l.pos < len(l.input) {
		ch := l.input[l.pos]

		if ch == '$' {
			// Check for ending delimiter
			endTag := l.peekDollarTag()
			if endTag == l.dolqstart {
				l.pos += len(endTag)
				l.state = stateInitial
				return Token{Type: lex_SCONST, Str: l.literalbuf.String(), Loc: l.start}
			}
		}

		l.literalbuf.WriteByte(ch)
		l.pos++
	}

	return l.failNear("unterminated dollar-quoted string", l.start)
}

// scanDollarTag scans and returns a dollar tag ($...$) if present.
func (l *Lexer) scanDollarTag() string {
	if l.pos >= len(l.input) || l.input[l.pos] != '$' {
		return ""
	}

	start := l.pos
	l.pos++ // skip first $

	// Tag can be empty ($$ ... $$) or have identifier chars
	for l.pos < len(l.input) {
		ch := l.input[l.pos]
		if ch == '$' {
			l.pos++
			return l.input[start:l.pos]
		}
		if l.pos == start+1 {
			// First char must be letter or underscore
			if !isIdentStart(ch) {
				l.pos = start
				return ""
			}
		} else {
			// Subsequent chars can include digits
			if !isIdentCont(ch) {
				l.pos = start
				return ""
			}
		}
		l.pos++
	}

	l.pos = start
	return ""
}

// peekDollarTag peeks at a dollar tag without advancing position.
func (l *Lexer) peekDollarTag() string {
	savedPos := l.pos
	tag := l.scanDollarTag()
	l.pos = savedPos
	return tag
}

// lexParam handles parameter tokens ($1, $2, etc.)
func (l *Lexer) lexParam() Token {
	l.pos++ // skip $
	start := l.pos
	for l.pos < len(l.input) && isDigit(l.input[l.pos]) {
		l.pos++
	}

	// Check for trailing junk
	if l.pos < len(l.input) && isIdentStart(l.input[l.pos]) {
		l.pos = l.identEnd(l.pos)
		return l.failNear("trailing junk after parameter", l.start)
	}

	val, _ := strconv.ParseInt(l.input[start:l.pos], 10, 64)
	return Token{Type: lex_PARAM, Ival: val, Loc: l.start}
}

// opRun is what lexOperator has learned about the run of operator characters
// it last scanned. A run of n characters can lex as up to n tokens (a run of
// '+' is n unary pluses), and each token is PostgreSQL's operator rule applied
// to the rest of the run, so scanning that rest afresh for every token is
// quadratic and, with the trailing +/- trim scanning back for a qualifying
// character once per character it trims, cubic. Each field below is instead
// found once and reused while it still holds for a later start: a token start
// only moves forward through a run, so every position of the run is examined a
// bounded number of times and lexing the run is linear in its length.
type opRun struct {
	end  int // the end of the run; 0 before the first run
	from int // the latest token start in the run; comment and special hold for it

	// comment is the first position after from at which "/*" or "--" begins
	// inside the run, or end when there is none.
	comment int
	// special is the first position at or after from holding one of
	// ~ ! @ # ^ & | ` ? %, which keeps a trailing + or - in the operator, or
	// end when there is none.
	special int
	// trimEnd is the untrimmed token end keep was found for, and keep the last
	// position before trimEnd, at or after the start it was found from, that
	// is not + or -: -1 when every one is.
	trimEnd, keep int
}

// lexOperator applies scan.l's operator rule at l.pos: the token is the
// maximal run of operator characters, cut where "/*" or "--" begins a comment
// inside it; then, unless it holds one of ~ ! @ # ^ & | ` ? %, every trailing
// + and - is trimmed (keeping at least one character), for SQL compatibility.
// An operator of NAMEDATALEN (64) bytes or more is an error, as in
// PostgreSQL. The rest of the run is lexed by the following tokens.
func (l *Lexer) lexOperator() Token {
	start := l.pos
	r := &l.opRun
	// A token start only moves forward, so start < r.from cannot happen
	// today; it rebuilds the run rather than trust caches found from a later
	// start, should a lookahead ever rewind into a run.
	if start < r.from || start >= r.end {
		end := start
		for end < len(l.input) && isOpChar(l.input[end]) {
			end++
			l.opScanSteps++
		}
		*r = opRun{end: end, from: start, comment: -1, special: -1, trimEnd: -1}
	}
	r.from = start

	// A comment cannot begin at start (lexInitial would have taken it), so
	// the search for a cut begins at start+1.
	if r.comment <= start {
		r.comment = r.end
		for q := start + 1; q+1 < r.end; q++ {
			l.opScanSteps++
			if c := l.input[q]; (c == '/' && l.input[q+1] == '*') || (c == '-' && l.input[q+1] == '-') {
				r.comment = q
				break
			}
		}
	}
	end := r.comment

	if end-start > 1 && isPlusMinus(l.input[end-1]) {
		if r.special < start {
			r.special = r.end
			for q := start; q < r.end; q++ {
				l.opScanSteps++
				if isOpSpecial(l.input[q]) {
					r.special = q
					break
				}
			}
		}
		if r.special >= end { // nothing qualifies: trim every trailing + and -
			if r.trimEnd != end {
				r.trimEnd, r.keep = end, -1
				for q := end - 1; q >= start; q-- {
					l.opScanSteps++
					if !isPlusMinus(l.input[q]) {
						r.keep = q
						break
					}
				}
			}
			end = max(r.keep, start) + 1
		}
	}

	l.pos = end
	op := l.input[start:end]

	// Single-char ops that should be returned as their char value
	if len(op) == 1 && isSelf(op[0]) {
		return Token{Type: int(op[0]), Str: op, Loc: l.start}
	}

	// Two-char special tokens
	if len(op) == 2 {
		switch op {
		case "=>":
			return Token{Type: lex_EQUALS_GREATER, Str: op, Loc: l.start}
		case ">=":
			return Token{Type: lex_GREATER_EQUALS, Str: op, Loc: l.start}
		case "<=":
			return Token{Type: lex_LESS_EQUALS, Str: op, Loc: l.start}
		case "<>":
			return Token{Type: lex_NOT_EQUALS, Str: op, Loc: l.start}
		case "!=":
			return Token{Type: lex_NOT_EQUALS, Str: op, Loc: l.start}
		}
	}

	if len(op) >= namedatalen {
		return l.failNear("operator too long", l.start)
	}

	return Token{Type: lex_Op, Str: op, Loc: l.start}
}

// lexNumber handles integer and numeric literals as scan.l's decinteger,
// numeric and real rules do, with their fail and junk rules: an underscore
// only separates two digits, and a literal followed by an identifier is
// trailing junk.
func (l *Lexer) lexNumber() Token {
	start := l.pos

	// Check for hex, octal, or binary prefix
	if l.input[l.pos] == '0' && l.pos+1 < len(l.input) {
		switch l.input[l.pos+1] {
		case 'x', 'X':
			return l.lexRadixNumber(isHexDigit, "invalid hexadecimal integer")
		case 'o', 'O':
			return l.lexRadixNumber(isOctalDigit, "invalid octal integer")
		case 'b', 'B':
			return l.lexRadixNumber(isBinaryDigit, "invalid binary integer")
		}
	}

	// Decimal integer, unless the literal starts with its decimal point
	if l.input[l.pos] != '.' {
		l.pos = scanDigits(l.input, l.pos, isDigit)
	}

	isFloat := false

	// Decimal point, unless it starts .. (numericfail: the integer is
	// returned and .. lexed next)
	if l.pos < len(l.input) && l.input[l.pos] == '.' && (l.pos+1 >= len(l.input) || l.input[l.pos+1] != '.') {
		l.pos++
		if l.pos < len(l.input) && isDigit(l.input[l.pos]) {
			l.pos = scanDigits(l.input, l.pos, isDigit)
		}
		isFloat = true
	}

	// Exponent; a sign with no digit after it is realfail
	if l.pos < len(l.input) && (l.input[l.pos] == 'e' || l.input[l.pos] == 'E') {
		p := l.pos + 1
		signed := p < len(l.input) && (l.input[p] == '+' || l.input[p] == '-')
		if signed {
			p++
		}
		switch {
		case p < len(l.input) && isDigit(l.input[p]):
			l.pos = scanDigits(l.input, p, isDigit)
			isFloat = true
		case signed:
			l.pos = p
			return l.failNear("trailing junk after numeric literal", start)
		}
	}

	// A literal followed by an identifier is junk
	if l.pos < len(l.input) && isIdentStart(l.input[l.pos]) {
		l.pos = l.identEnd(l.pos)
		return l.failNear("trailing junk after numeric literal", start)
	}

	numStr := l.input[start:l.pos]
	// Remove underscores for parsing
	numStr = strings.ReplaceAll(numStr, "_", "")

	if isFloat {
		return Token{Type: lex_FCONST, Str: numStr, Loc: l.start}
	}

	val, ok := integerLiteral(numStr, false)
	if !ok {
		// Too large, treat as float
		return Token{Type: lex_FCONST, Str: numStr, Loc: l.start}
	}

	return Token{Type: lex_ICONST, Ival: val, Str: numStr, Loc: l.start}
}

// scanDigits is the end of the integer at p, whose first byte is a digit:
// digits, each optionally preceded by one underscore, as scan.l's
// {digit}(_?{digit})*.
func scanDigits(s string, p int, digit func(byte) bool) int {
	p++
	for p < len(s) {
		switch {
		case digit(s[p]):
			p++
		case s[p] == '_' && p+1 < len(s) && digit(s[p+1]):
			p += 2
		default:
			return p
		}
	}
	return p
}

// identEnd is the end of the identifier starting at p: an identifier start
// byte and the identifier bytes after it.
func (l *Lexer) identEnd(p int) int {
	p++
	for p < len(l.input) && isIdentCont(l.input[p]) {
		p++
	}
	return p
}

// lexRadixNumber handles 0x, 0o and 0b integers as scan.l's hexinteger,
// octinteger and bininteger rules do: 0x(_?{hexdigit})+. A prefix with no
// digit is the fail rule's error (0x, 0x_), unless the identifier after the
// 0 runs longer, which is decinteger_junk, as flex takes the longest match.
func (l *Lexer) lexRadixNumber(digit func(byte) bool, invalid string) Token {
	start := l.pos
	p := start + 2
	if p < len(l.input) && l.input[p] == '_' {
		p++
	}
	valid := p < len(l.input) && digit(l.input[p])
	if valid {
		p = scanDigits(l.input, p, digit)
	}
	l.pos = p

	if junk := l.identEnd(start + 1); junk > l.pos {
		l.pos = junk
		return l.failNear("trailing junk after numeric literal", start)
	}
	if !valid {
		return l.failNear(invalid, start)
	}

	numStr := l.input[start:l.pos]
	numStr = strings.ReplaceAll(numStr, "_", "")

	val, ok := integerLiteral(numStr, false)
	if !ok {
		return Token{Type: lex_FCONST, Str: numStr, Loc: l.start}
	}

	return Token{Type: lex_ICONST, Ival: val, Str: numStr, Loc: l.start}
}

// integerLiteral is the value of an integer literal's text as the scanner
// accepted it, underscores removed: decimal digits, or 0x, 0o or 0b (either
// case) and digits of that radix. negative reads it as the literal's
// negation, so the least int64 (-9223372036854775808, -0x8000000000000000)
// has a value although its magnitude does not. ok is false when the value
// does not fit int64, or the text is not an integer literal (1.5, 1e3).
func integerLiteral(text string, negative bool) (val int64, ok bool) {
	base, digits := 10, text
	if len(text) > 2 && text[0] == '0' {
		switch text[1] {
		case 'x', 'X':
			base, digits = 16, text[2:]
		case 'o', 'O':
			base, digits = 8, text[2:]
		case 'b', 'B':
			base, digits = 2, text[2:]
		}
	}
	if digits == "" || digits[0] == '+' || digits[0] == '-' {
		return 0, false
	}
	if negative {
		digits = "-" + digits
	}
	val, err := strconv.ParseInt(digits, base, 64)
	if err != nil {
		return 0, false
	}
	return val, true
}

// lexIdent handles identifiers and keywords.
func (l *Lexer) lexIdent() Token {
	start := l.pos

	// Scan identifier
	for l.pos < len(l.input) && isIdentCont(l.input[l.pos]) {
		l.pos++
	}

	ident := l.input[start:l.pos]

	// Check if it's a keyword
	kw := LookupKeyword(ident)
	if kw != nil {
		return Token{Type: kw.Token, Str: kw.Name, Loc: l.start}
	}

	// Convert to lowercase for non-keywords
	ident = downcase(ident)

	return Token{Type: lex_IDENT, Str: l.truncateIdentifier(ident), Loc: l.start}
}

// namedatalen is PostgreSQL's NAMEDATALEN; identifiers keep at most
// namedatalen-1 bytes.
const namedatalen = 64

// truncateIdentifier mirrors PostgreSQL's truncate_identifier: an identifier
// of namedatalen bytes or more is clipped on a character boundary
// (pg_mbcliplen) to at most namedatalen-1 bytes, and the clip is reported as
// NOTICE 42622 (ERRCODE_NAME_TOO_LONG) with PostgreSQL's message text.
func (l *Lexer) truncateIdentifier(ident string) string {
	if len(ident) < namedatalen {
		return ident
	}
	truncated := ident[:mbcliplen(ident, namedatalen-1)]
	if l.noticeHandler != nil {
		l.noticeHandler(Notice{
			Code:    "42622",
			Message: fmt.Sprintf("identifier \"%s\" will be truncated to \"%s\"", ident, truncated),
		})
	}
	return truncated
}

// mbcliplen mirrors pg_mbcliplen for UTF-8: the byte length of the longest
// prefix of whole characters, each sized by its lead byte as pg_utf_mblen
// does, that fits in limit bytes.
func mbcliplen(s string, limit int) int {
	n := 0
	for n < len(s) {
		w := utf8MbLen(s[n])
		if n+w > limit {
			break
		}
		n += w
	}
	return n
}

// utf8MbLen mirrors pg_utf_mblen: a character's byte length from its lead
// byte, with any byte that cannot lead a sequence counting as one.
func utf8MbLen(b byte) int {
	switch {
	case b&0x80 == 0:
		return 1
	case b&0xe0 == 0xc0:
		return 2
	case b&0xf0 == 0xe0:
		return 3
	case b&0xf8 == 0xf0:
		return 4
	default:
		return 1
	}
}

// downcase mirrors PostgreSQL's downcase_identifier in a multibyte encoding
// such as UTF-8: only ASCII 'A'..'Z' are lowercased, every other byte is
// kept, so the byte length never changes. s is returned as is when it has no
// ASCII uppercase letter.
func downcase(s string) string {
	i := 0
	for i < len(s) && !isASCIIUpper(s[i]) {
		i++
	}
	if i == len(s) {
		return s
	}
	var b strings.Builder
	b.Grow(len(s))
	b.WriteString(s[:i])
	for ; i < len(s); i++ {
		c := s[i]
		if isASCIIUpper(c) {
			c += 'a' - 'A'
		}
		b.WriteByte(c)
	}
	return b.String()
}

func isASCIIUpper(c byte) bool {
	return c >= 'A' && c <= 'Z'
}

// Character classification functions

func isDigit(ch byte) bool {
	return ch >= '0' && ch <= '9'
}

func isHexDigit(ch byte) bool {
	return (ch >= '0' && ch <= '9') || (ch >= 'a' && ch <= 'f') || (ch >= 'A' && ch <= 'F')
}

func isOctalDigit(ch byte) bool {
	return ch >= '0' && ch <= '7'
}

func isBinaryDigit(ch byte) bool {
	return ch == '0' || ch == '1'
}

func hexValue(ch byte) int {
	if ch >= '0' && ch <= '9' {
		return int(ch - '0')
	}
	if ch >= 'a' && ch <= 'f' {
		return int(ch - 'a' + 10)
	}
	return int(ch - 'A' + 10)
}

func isIdentStart(ch byte) bool {
	// A-Z, a-z, _, and high bytes (for UTF-8)
	return (ch >= 'A' && ch <= 'Z') || (ch >= 'a' && ch <= 'z') || ch == '_' || ch >= 128
}

func isIdentCont(ch byte) bool {
	// A-Z, a-z, 0-9, _, $, and high bytes
	return isIdentStart(ch) || (ch >= '0' && ch <= '9') || ch == '$'
}

func isSelf(ch byte) bool {
	// Characters that are self-delimiting tokens
	return ch == ',' || ch == '(' || ch == ')' || ch == '[' || ch == ']' ||
		ch == '.' || ch == ';' || ch == ':' || ch == '+' || ch == '-' ||
		ch == '*' || ch == '/' || ch == '%' || ch == '^' || ch == '<' ||
		ch == '>' || ch == '='
}

func isSelfOnly(ch byte) bool {
	// Characters that are ONLY self-delimiting (not part of operators)
	return ch == ',' || ch == '(' || ch == ')' || ch == '[' || ch == ']' ||
		ch == '.' || ch == ';' || ch == ':'
}

// isPlusMinus reports whether ch is + or -, which an operator may not end in
// unless it holds a character isOpSpecial accepts.
func isPlusMinus(ch byte) bool {
	return ch == '+' || ch == '-'
}

// isOpSpecial reports whether ch is one of the operator characters that are
// not SQL-standard operator characters (scan.l's check before trimming a
// trailing + or -).
func isOpSpecial(ch byte) bool {
	return ch == '~' || ch == '!' || ch == '@' || ch == '#' || ch == '^' ||
		ch == '&' || ch == '|' || ch == '`' || ch == '?' || ch == '%'
}

func isOpChar(ch byte) bool {
	// Characters that can appear in operators
	return ch == '~' || ch == '!' || ch == '@' || ch == '#' || ch == '^' ||
		ch == '&' || ch == '|' || ch == '`' || ch == '?' || ch == '+' ||
		ch == '-' || ch == '*' || ch == '/' || ch == '%' || ch == '<' ||
		ch == '>' || ch == '='
}

// Unicode surrogate pair handling

func isUTF16SurrogateFirst(r rune) bool {
	return r >= 0xD800 && r <= 0xDBFF
}

func isUTF16SurrogateSecond(r rune) bool {
	return r >= 0xDC00 && r <= 0xDFFF
}

func surrogateToCodepoint(high, low rune) rune {
	return ((high - 0xD800) << 10) + (low - 0xDC00) + 0x10000
}

// isValidUnicodeCodepoint checks if a code point is valid.
func isValidUnicodeCodepoint(r rune) bool {
	return r <= unicode.MaxRune && !isUTF16SurrogateFirst(r) && !isUTF16SurrogateSecond(r)
}

func isSpaceByte(c byte) bool {
	return c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f' || c == '\v'
}

// scanUESCAPE attempts to scan a UESCAPE clause.
// It returns the escape character (default backslash) and any error encountered.
// If no UESCAPE clause is present, it returns '\\' and nil.
// If a UESCAPE clause is present but invalid, it rewinds and returns '\\', nil,
// effectively treating "UESCAPE" as the next token.
func (l *Lexer) scanUESCAPE() (rune, error) {
	escapeChar := '\\'
	savedPos := l.pos

	l.skipWhitespaceAndComments()

	if l.pos+7 <= len(l.input) {
		word := l.input[l.pos : l.pos+7]
		if strings.EqualFold(word, "UESCAPE") {
			l.pos += 7
			l.skipWhitespaceAndComments()

			if l.pos < len(l.input) && l.input[l.pos] == '\'' {
				l.pos++
				if l.pos < len(l.input) {
					ch := l.input[l.pos]
					escapeChar = rune(ch)
					l.pos++

					if ch == '\'' && l.pos < len(l.input) && l.input[l.pos] == '\'' {
						escapeChar = '\''
						l.pos++
					}

					if l.pos < len(l.input) && l.input[l.pos] == '\'' {
						l.pos++
						return escapeChar, nil
					}
				}
			}
			// Invalid UESCAPE clause, rollback
			l.pos = savedPos
			return '\\', nil
		}
	}

	l.pos = savedPos
	return '\\', nil
}

// skipWhitespaceAndComments skips whitespace and comments (both -- and /* */).
func (l *Lexer) skipWhitespaceAndComments() {
	for l.pos < len(l.input) {
		ch := l.input[l.pos]

		if isSpaceByte(ch) {
			l.pos++
			continue
		}

		if ch == '-' && l.pos+1 < len(l.input) && l.input[l.pos+1] == '-' {
			l.skipLineComment()
			continue
		}

		if ch == '/' && l.pos+1 < len(l.input) && l.input[l.pos+1] == '*' {
			l.pos += 2
			depth := 1
			for l.pos < len(l.input) && depth > 0 {
				if l.pos >= len(l.input) {
					break
				}
				if l.input[l.pos] == '*' && l.pos+1 < len(l.input) && l.input[l.pos+1] == '/' {
					depth--
					l.pos += 2
				} else if l.input[l.pos] == '/' && l.pos+1 < len(l.input) && l.input[l.pos+1] == '*' {
					depth++
					l.pos += 2
				} else {
					l.pos++
				}
			}
			continue
		}

		break
	}
}

// decodeUnicodeString decodes the body s of a U& string or identifier that
// starts at at, as parser.c's str_udeescape does. PostgreSQL reports an error
// at at+3+i, i the offset in s of the escape it refuses (the 3 is U&').
func (l *Lexer) decodeUnicodeString(s string, escape byte, at int) (string, bool) {
	var buf strings.Builder
	var pairFirst rune
	i := 0
	for i < len(s) {
		if s[i] != escape {
			if pairFirst != 0 {
				return "", l.badUnicode("invalid Unicode surrogate pair", at+3+i, "")
			}
			buf.WriteByte(s[i])
			i++
			continue
		}
		var c int64
		var n int
		switch {
		case i+1 < len(s) && s[i+1] == escape:
			if pairFirst != 0 {
				return "", l.badUnicode("invalid Unicode surrogate pair", at+3+i, "")
			}
			buf.WriteByte(escape)
			i += 2
			continue
		case i+5 <= len(s) && allHex(s[i+1:i+5]):
			c, _ = strconv.ParseInt(s[i+1:i+5], 16, 32)
			n = 5
		case i+8 <= len(s) && s[i+1] == '+' && allHex(s[i+2:i+8]):
			c, _ = strconv.ParseInt(s[i+2:i+8], 16, 32)
			n = 8
		default:
			return "", l.badUnicode("invalid Unicode escape", at+3+i, "Unicode escapes must be \\XXXX or \\+XXXXXX.")
		}
		r := rune(c)
		if r == 0 || r > unicode.MaxRune {
			return "", l.badUnicode("invalid Unicode escape value", at+3+i, "")
		}
		switch {
		case pairFirst != 0 && isUTF16SurrogateSecond(r):
			r = surrogateToCodepoint(pairFirst, r)
			pairFirst = 0
		case pairFirst != 0 || isUTF16SurrogateSecond(r):
			return "", l.badUnicode("invalid Unicode surrogate pair", at+3+i, "")
		}
		if isUTF16SurrogateFirst(r) {
			pairFirst = r
		} else {
			buf.WriteRune(r)
		}
		i += n
	}
	if pairFirst != 0 {
		return "", l.badUnicode("invalid Unicode surrogate pair", at+3+len(s), "")
	}
	return buf.String(), true
}

// badUnicode records a U& escape error, 42601 with no "at or near" text as
// parser.c reports it, and is false.
func (l *Lexer) badUnicode(message string, at int, hint string) bool {
	l.failAt(codeSyntaxError, message, at, hint)
	return false
}

// failNear records message as scan.l's yyerror reports it, followed by the
// text from at to the scanner's position ("at or near"), or by "at end of
// input" when at is the end, and ends the token stream.
func (l *Lexer) failNear(message string, at int) Token {
	if at >= len(l.input) {
		message += " at end of input"
	} else {
		message += " at or near \"" + l.input[at:l.pos] + "\""
	}
	return l.failAt(codeSyntaxError, message, at, "")
}

// failAt records the lexer's first error, at the 0-based offset at, and ends
// the token stream: the lexer returns EOF from here on, as PostgreSQL's
// scanner stops at its first error.
func (l *Lexer) failAt(code, message string, at int, hint string) Token {
	if l.Err == nil {
		l.Err = &ParseError{Code: code, Message: message, Hint: hint, Position: at}
	}
	l.state = stateInitial
	l.pos = len(l.input)
	return Token{Type: lex_EOF, Loc: at}
}
