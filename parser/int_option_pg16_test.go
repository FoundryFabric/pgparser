// TestIntOptionIsPostgreSQL16s pins PostgreSQL 16's answers for 10 ALTER
// COLUMN ... SET STATISTICS and SET GENERATED statements, and malformed
// ones.
func TestIntOptionIsPostgreSQL16s(t *testing.T) {
	checkPG16Answers(t, "testdata/int_option_pg16.jsonl", 10)
}

// TestIntOptionIsAnInteger requires SET STATISTICS's target and SET
// GENERATED's kind to be a bare Integer, as PostgreSQL 16's makeInteger
// makes them, not a constant expression.
func TestIntOptionIsAnInteger(t *testing.T) {
	for sql, want := range map[string]int64{
		"alter table t alter column a set statistics -1":  -1,
		"alter index i alter column 1 set statistics 100": 100,
		"alter table t alter a set generated by default":  'd',
	} {
		list, err := Parse(sql)
		if err != nil {
			t.Fatal(err)
		}
		def := list.Items[0].(*nodes.AlterTableStmt).Cmds.Items[0].(*nodes.AlterTableCmd).Def
		if l, ok := def.(*nodes.List); ok {
			def = l.Items[0].(*nodes.DefElem).Arg
		}
		if i, ok := def.(*nodes.Integer); !ok || i.Ival != want {
			t.Errorf("%s: %#v, want Integer %d", sql, def, want)
		}
	}
}
