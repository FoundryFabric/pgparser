package parser

import (
	"testing"

	"github.com/pgplex/pgparser/nodes"
)

// TestParseAddIdentityHasItsConstraint pins ALTER ... ADD GENERATED ... AS
// IDENTITY's shape, with and without COLUMN: an AT_AddIdentity command whose
// Def is the identity constraint, with GENERATED's position and the sequence
// options, as PostgreSQL 16 builds it.
func TestParseAddIdentityHasItsConstraint(t *testing.T) {
	for _, c := range []struct {
		sql     string
		when    byte
		options int
		loc     nodes.ParseLoc
	}{
		{"alter table t alter column c add generated always as identity", 'a', 0, 33},
		{"alter table t alter column c add generated by default as identity (start 1 increment 2)", 'd', 2, 33},
		{"alter table t alter c add generated always as identity (start 1)", 'a', 1, 26},
	} {
		stmts, err := Parse(c.sql)
		if err != nil {
			t.Fatalf("Parse(%q): %v", c.sql, err)
		}
		cmd := stmts.Items[0].(*nodes.AlterTableStmt).Cmds.Items[0].(*nodes.AlterTableCmd)
		con, ok := cmd.Def.(*nodes.Constraint)
		if cmd.Subtype != int(nodes.AT_AddIdentity) || cmd.Name != "c" || !ok {
			t.Errorf("Parse(%q): %#v, want AT_AddIdentity of c with a Constraint", c.sql, cmd)
			continue
		}
		if con.Contype != nodes.CONSTR_IDENTITY || con.GeneratedWhen != c.when || con.Location != c.loc || con.Options.Len() != c.options {
			t.Errorf("Parse(%q): Constraint{%v, %q, at %d, %d options}, want {CONSTR_IDENTITY, %q, at %d, %d options}",
				c.sql, con.Contype, con.GeneratedWhen, con.Location, con.Options.Len(), c.when, c.loc, c.options)
		}
	}
}
